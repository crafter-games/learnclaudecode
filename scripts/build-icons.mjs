// Generates src/components/game/icons.tsx from the downloaded game-icons.net SVGs
// (assets/sprites/icons, CC BY 3.0 — see CREDITS.md). Re-run after adding icons.
import fs from "node:fs";
import path from "node:path";

const dir = "assets/sprites/icons";
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const svg = fs.readFileSync(path.join(dir, f), "utf8");
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).filter((d) => d !== "M0 0h512v512H0z");
    return [f.replace(/\.svg$/, ""), paths.join(" ")];
  });

const body = `// GENERATED by scripts/build-icons.mjs from game-icons.net (CC BY 3.0). Do not edit by hand.
import type { SVGProps } from "react";

const PATHS = {
${entries.map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`).join("\n")}
} as const;

export type GameIconName = keyof typeof PATHS;

export function GameIcon({ name, size = 24, ...rest }: { name: GameIconName; size?: number } & SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="0 0 512 512" width={size} height={size} fill="currentColor" aria-hidden="true" focusable="false" {...rest}>
      <path d={PATHS[name]} />
    </svg>
  );
}
`;
fs.writeFileSync("src/components/game/icons.tsx", body);
console.log(`${entries.length} icons`);
